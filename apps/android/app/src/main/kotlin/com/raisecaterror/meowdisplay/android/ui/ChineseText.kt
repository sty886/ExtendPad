    fun translate(text: String): String {
        exact[text]?.let { return it }
        // Settings section headings are uppercased by the existing UI code.
        exact.entries.firstOrNull { it.key.equals(text, ignoreCase = true) }?.value?.let { return it }
        if (!text.any { it in 'A'..'Z' || it in 'a'..'z' }) return text
        // Connected status is assembled from individually known labels. Translate
        // those labels before handling longer phrases so no English part leaks.
        var translated = text.split(" · ").joinToString(" · ") { exact[it] ?: it }
        for ((english, chinese) in phrases) translated = translated.replace(english, chinese)
        return translated
    }
